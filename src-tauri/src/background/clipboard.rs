//! Historial local del portapapeles.
//!
//! macOS no notifica los cambios de `NSPasteboard`: se compara su `changeCount` una
//! vez por segundo, una lectura local sin coste apreciable. Sin consentimiento o en
//! pausa, el hilo duerme hasta que cambian las preferencias.
//!
//! No se guarda nada marcado como oculto o transitorio (convención de nspasteboard.org
//! que siguen los gestores de contraseñas), nada copiado desde una app excluida ni, por
//! defecto, texto con aspecto de credencial.

